def read_config():
    """The campaign name, the base URL, the Drive folder and the file names all live in
    index.html. Parsing them here is what stops this menu becoming a second place to edit."""
    html = open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()

    def one(pattern, what):
        m = re.search(pattern, html, re.S)
        if not m:
            sys.exit('index.html: could not find %s — has its config block moved?' % what)
        return m.group(1)

    base  = one(r'const\s+BASE\s*=\s*"([^"]+)"', 'the BASE constant')
    name  = one(r'const\s+CAMPAIGN\s*=\s*\{[^}]*?name:\s*"([^"]+)"', "CAMPAIGN.name")
    drive = re.search(r'driveFolder:\s*"([^"]*)"', html)
    files_src = one(r'const\s+FILES\s*=\s*\{(.*?)\}', 'the FILES map')
    files = dict(re.findall(r'(\w+)\s*:\s*"([^"]+)"', files_src))

    missing = [t['key'] for t in TOOLS if t['key'] not in files]
    if missing:
        sys.exit('index.html FILES is missing: %s' % ', '.join(missing))
    return dict(base=base, name=name, drive=(drive.group(1) if drive else ''), files=files)


def block_for(page, cfg):
    tools = [dict(key=t['key'], file=cfg['files'][t['key']], name=t['name'].replace('&amp;', '&'),
                  desc=t['desc'], dm=t['dm'], ico=t['ico']) for t in TOOLS]
    extras = [
        dict(label='Portal', href=cfg['base'] + 'index.html', external=False,
             ico='<path d="m3 10 9-7 9 7v9a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2Z"/><path d="M9 21v-8h6v8"/>'),
        dict(label='Shared folder', href=cfg['drive'], external=True,
             ico='<path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"/><polyline points="7 10 12 15 17 10"/><line x1="12" x2="12" y1="15" y2="3"/>'),
        dict(label='Licensing', href=cfg['base'] + 'legal.html', external=False,
             ico='<path d="M12 3v18"/><path d="M5 7h14"/><path d="m5 7-2 6a3 3 0 0 0 6 0Z"/><path d="m19 7 2 6a3 3 0 0 1-6 0Z"/>'),
    ]
    js = (JS.replace('@@HERE@@', page)
            .replace('@@BASE@@', cfg['base'])
            .replace('@@CAMPAIGN@@', json.dumps(dict(name=cfg['name'])))
            .replace('@@TOOLS@@', json.dumps(tools))
            .replace('@@EXTRAS@@', json.dumps(extras)))
    return '%s\n%s\n%s\n%s\n' % (OPEN, CSS, js, CLOSE)


def process(path, cfg, check):
    page = os.path.basename(path)
    html = open(path, encoding='utf-8', newline='').read()
    want = block_for(page, cfg)
    have = BLOCK_RE.search(html)

    if check:
        if not have:                       return (page, 'MISSING', False)
        if have.group(0) != want:          return (page, 'STALE — config changed since it was built', False)
        return (page, 'ok', True)

    body = BLOCK_RE.sub('', html)
    if STAMP_OPEN in body:
        i = body.index(STAMP_OPEN)         # keep the build stamp last
    else:
        i = body.rindex('</body>')
    open(path, 'w', encoding='utf-8', newline='').write(body[:i] + want + body[i:])
    return (page, 'unchanged' if (have and have.group(0) == want) else
                  ('written' if not have else 'updated'), True)


def main():
    check   = '--check' in sys.argv
    args    = [a for a in sys.argv[1:] if not a.startswith('--')]
    targets = args or [os.path.join(ROOT, p) for p in PAGES]
    cfg     = read_config()
    print('  config from index.html: %s · %s' % (cfg['name'], cfg['base']))
    allok = True
    for t in targets:
        if not os.path.exists(t):
            print('  %-30s missing' % os.path.basename(t)); allok = False; continue
        page, msg, good = process(t, cfg, check)
        print('  %-30s %s' % (page, msg))
        allok = allok and good
    if check and not allok:
        print('\nNavigation is stale or missing — run tools/build_nav.py'); sys.exit(1)


if __name__ == '__main__':
    main()
