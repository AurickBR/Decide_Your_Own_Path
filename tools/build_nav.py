#!/usr/bin/env python3
"""Write the campaign navigation menu into every published page.

Why a script and not five hand-edited copies: the menu names every tool on the site, so five
hand-maintained copies would be five chances to leave a renamed file behind — exactly the failure
HOSTING_AND_DEPLOYMENT.md §6 records ("a rename must reach GitHub and the hub in the same commit").
This keeps index.html as the ONE place links live: the campaign name, the base URL, the Drive
folder and the file names are read out of index.html's config block and compiled into the menu.

    python3 tools/build_nav.py            # write the block into every page
    python3 tools/build_nav.py --check    # verify, change nothing (exit 1 if stale or missing)

Idempotent: an existing block is removed before the new one is written, so re-running with no
config change rewrites the same bytes.

The emitted block is byte-identical in every page apart from one line — the `HERE` constant naming
the file it sits in, which is what marks "you are here" in the menu. test/nav.test.js asserts that.

Insertion point is immediately before the build stamp (or before </body> when a page has no stamp
yet), so tools/stamp_build.py keeps the last word and the stamp still covers the menu's bytes.
"""
